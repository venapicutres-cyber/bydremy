-- Checkout publik hanya membuat pesanan; aktivasi undangan hanya dilakukan
-- oleh Edge Function setelah pembayaran dinyatakan lunas (kini: persetujuan
-- admin atas bukti transfer manual, bukan gateway otomatis).

alter table public.pages alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.pages', 'id'), greatest(coalesce((select max(id) from public.pages), 1), 1), true);

alter table public.orders
  add column if not exists checkout_key uuid,
  add column if not exists checkout_token text,
  add column if not exists payment_status text not null default 'unpaid',
  add column if not exists payment_provider text,
  add column if not exists payment_reference text,
  add column if not exists payment_url text,
  add column if not exists payment_expires_at timestamptz,
  add column if not exists invitation_id bigint references public.pages(id) on delete set null,
  add column if not exists auth_user_id uuid references auth.users(id) on delete set null,
  add column if not exists activated_at timestamptz;

create unique index if not exists orders_checkout_key_unique on public.orders (checkout_key) where checkout_key is not null;
create unique index if not exists orders_checkout_token_unique on public.orders (checkout_token) where checkout_token is not null;
create index if not exists orders_payment_reference_idx on public.orders (payment_reference) where payment_reference is not null;
create index if not exists orders_invitation_id_idx on public.orders (invitation_id) where invitation_id is not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'orders_payment_status_check' and conrelid = 'public.orders'::regclass
  ) then
    alter table public.orders add constraint orders_payment_status_check
      check (payment_status in ('unpaid', 'pending', 'settlement', 'failed', 'expired'));
  end if;
end $$;

create or replace function public.create_checkout_order(
  p_template_id bigint,
  p_customer_name text,
  p_email text,
  p_phone text,
  p_checkout_key uuid
)
returns table (
  order_id text,
  checkout_token text,
  customer_name text,
  email text,
  phone text,
  template_name text,
  total bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_template public.pages;
  v_order public.orders;
  v_name text := btrim(coalesce(p_customer_name, ''));
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_phone text := btrim(coalesce(p_phone, ''));
begin
  if p_checkout_key is null then
    raise exception 'Checkout key tidak valid.' using errcode = '22023';
  end if;
  if char_length(v_name) not between 2 and 100 then
    raise exception 'Nama harus 2-100 karakter.' using errcode = '22023';
  end if;
  if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Email tidak valid.' using errcode = '22023';
  end if;
  if char_length(v_phone) not between 8 and 30 then
    raise exception 'Nomor WhatsApp tidak valid.' using errcode = '22023';
  end if;

  select * into v_order from public.orders where checkout_key = p_checkout_key;
  if found then
    return query
      select v_order.id, v_order.checkout_token, v_order.customer_name, v_order.email, v_order.phone,
             coalesce((select template_name from public.pages where id = v_order.template_id), ''), v_order.total;
    return;
  end if;

  select * into v_template
  from public.pages
  where id = p_template_id and kind = 'template' and status = 'published';
  if not found or coalesce(v_template.price, 0) <= 0 then
    raise exception 'Template tidak tersedia untuk checkout.' using errcode = '22023';
  end if;

  insert into public.orders (
    id, checkout_key, checkout_token, customer_name, email, phone, template_id, package_name,
    status, payment_status, total, paid, date, notes
  ) values (
    'ORD-' || upper(substr(md5(clock_timestamp()::text || random()::text), 1, 12)),
    p_checkout_key,
    md5(clock_timestamp()::text || random()::text || p_checkout_key::text),
    v_name, v_email, v_phone, v_template.id, coalesce(v_template.template_name, v_template.label),
    'pending', 'pending', v_template.price, 0, current_date, 'Checkout mandiri'
  ) returning * into v_order;

  return query select v_order.id, v_order.checkout_token, v_order.customer_name, v_order.email, v_order.phone,
    coalesce(v_template.template_name, v_template.label), v_order.total;
end;
$$;

revoke all on function public.create_checkout_order(bigint, text, text, text, uuid) from public;
grant execute on function public.create_checkout_order(bigint, text, text, text, uuid) to anon, authenticated;

create or replace function public.checkout_status(p_order_id text, p_checkout_token text)
returns table (payment_status text, invitation_route text, activated boolean)
language sql
security definer
set search_path = public
as $$
  select o.payment_status, p.route, o.activated_at is not null
  from public.orders o
  left join public.pages p on p.id = o.invitation_id
  where o.id = p_order_id and o.checkout_token = p_checkout_token
  limit 1;
$$;

revoke all on function public.checkout_status(text, text) from public;
grant execute on function public.checkout_status(text, text) to anon, authenticated;

create or replace function public.activate_paid_order(p_order_id text, p_auth_user_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_template public.pages;
  v_page_id bigint;
  v_slug text;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Pesanan tidak ditemukan.' using errcode = '23503';
  end if;
  if v_order.payment_status <> 'settlement' then
    raise exception 'Pembayaran belum lunas.' using errcode = '42501';
  end if;
  if v_order.invitation_id is not null then
    return v_order.invitation_id;
  end if;

  select * into v_template from public.pages where id = v_order.template_id and kind = 'template';
  if not found then
    raise exception 'Template pesanan tidak ditemukan.' using errcode = '23503';
  end if;

  v_slug := 'undangan-' || lower(replace(v_order.id, 'ORD-', ''));
  insert into public.pages (
    slug, route, label, title, description, category, sort_order, template_name, file, css, thumb,
    status, kind, price, price_compare, content_html, hidden_section_ids, text_overrides,
    image_overrides, link_overrides, extra_html, views
  ) values (
    v_slug, '/u/' || v_slug, v_order.customer_name, v_order.customer_name || ' · Wedding Invitation',
    v_template.description, v_template.category, 0, v_template.template_name, v_template.file,
    v_template.css, v_template.thumb, 'draft', 'page', null, null, v_template.content_html,
    v_template.hidden_section_ids, v_template.text_overrides, v_template.image_overrides,
    v_template.link_overrides, v_template.extra_html, 0
  ) returning id into v_page_id;

  update public.orders
  set invitation_id = v_page_id,
      auth_user_id = coalesce(p_auth_user_id, auth_user_id),
      activated_at = now(),
      status = 'in_progress',
      paid = total,
      paid_at = current_date
  where id = p_order_id;

  return v_page_id;
end;
$$;

revoke all on function public.activate_paid_order(text, uuid) from public;
grant execute on function public.activate_paid_order(text, uuid) to service_role;
