import { chromium } from 'playwright-core';
const CHROME = 'C:/Users/PC - SIGAMPANG/AppData/Local/ms-playwright/chromium-1255/chrome-win64/chrome.exe';
const b = await chromium.launch({ executablePath: CHROME, headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem('bydreamy.admin.session', JSON.stringify({email:'admin@bydreamy.com',name:'Admin bydreamy',role:'admin',loginAt:new Date().toISOString()})));
const p = await ctx.newPage();
p.on('pageerror', e => console.log('PAGEERROR', e.message.slice(0,200)));
await p.goto('http://localhost:3000/admin/navigation', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(700);
await p.getByRole('button', { name: /Tambah item menu/ }).click();
const labels = p.locator('input[aria-label="Label menu"]');
console.log('rows', await labels.count());
await labels.last().fill('QA Menu');
await p.getByRole('button', { name: /Simpan Perubahan/ }).click();
await p.waitForTimeout(400);
console.log('stored nav', await p.evaluate(() => JSON.parse(localStorage.getItem('bydreamy.admin.v1')).navigation.map(n=>n.label)));
await p.goto('http://localhost:3000/tentang', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(700);
console.log('has QA Menu', (await p.locator('body').innerText()).includes('QA Menu'));
console.log('nav text', await p.locator('.site-nav').innerText());
await b.close();
